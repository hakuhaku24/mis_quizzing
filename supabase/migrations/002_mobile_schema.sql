-- 002_mobile_schema.sql
-- Supersedes 001_initial_schema.sql, which normalized school/department/subject
-- into separate FK tables — a design the app never actually used. This mirrors
-- the real, working SQLite schema (data/questions.db) column-for-column so the
-- existing pipeline/API logic ports over with minimal translation, plus
-- per-user scoping (auth.uid()) for user_attempts / user_question_states so
-- the mobile app can eventually support more than one person's data safely.

create extension if not exists "pgcrypto";

-- "by default" (not "always") so the SQLite→Supabase migration script can
-- insert explicit ids matching data/questions.db, preserving the
-- questions<->solutions foreign key without a remapping pass.
create table questions (
  id                     bigint generated by default as identity primary key,
  school                 text,
  department             text,
  year_label             text,
  exam_year              int,
  question_number        text,
  question_text          text not null,
  question_type          text,   -- essay | short_answer | multiple_choice | calculation
  topic                  text,
  subtopic               text,
  difficulty             int check (difficulty between 1 and 5),
  value_score            numeric,
  source_type            text,   -- pdf_extracted | template
  extraction_confidence  numeric,
  verified_status        text default 'unverified',
  options                jsonb,  -- MC choices
  correct_option         text,  -- 'A'|'B'|'C'|'D'|'E'
  concepts               jsonb,  -- knowledge-point tags
  source_page_start      int,
  source_page_end        int,
  created_at             timestamptz default now()
);

create table solutions (
  id               bigint generated by default as identity primary key,
  question_id      bigint not null references questions(id) on delete cascade,
  solution_text    text not null,
  explanation      text,
  source_type      text,   -- ai_draft | template | human_written
  verified_status  text default 'unverified',
  created_at       timestamptz default now()
);

create table user_attempts (
  id                   bigint generated always as identity primary key,
  user_id              uuid not null default auth.uid(),
  question_id          bigint references questions(id),
  answer_text          text,
  selected_option      text,
  is_correct           boolean,
  self_assessment      text,   -- correct | partial | wrong
  confidence           text,   -- low | medium | high
  error_type           text,   -- concept | memory | careless | unseen
  ai_score             int,
  ai_feedback          jsonb,
  srs_applied          boolean default false,
  time_spent_seconds   int,
  created_at           timestamptz default now()
);

create table user_question_states (
  id               bigint generated always as identity primary key,
  user_id          uuid not null default auth.uid(),
  question_id      bigint not null references questions(id),
  status           text default 'new',  -- new | learning | wrong | reviewing | mastered
  last_attempt_at  timestamptz,
  mastery_score    numeric default 0,
  wrong_count      int default 0,
  correct_count    int default 0,
  next_review_at   timestamptz,
  interval_days    numeric default 0,
  ease             numeric default 2.5,
  reps             int default 0,
  updated_at       timestamptz default now(),
  unique (user_id, question_id)
);

create index questions_topic_idx       on questions(topic);
create index questions_school_idx      on questions(school);
create index questions_value_score_idx on questions(value_score desc);
create index attempts_user_idx         on user_attempts(user_id);
create index attempts_question_idx     on user_attempts(question_id);
create index states_user_idx           on user_question_states(user_id);
create index states_next_review_idx    on user_question_states(next_review_at);

-- Questions/solutions are shared read-only content (same question bank for
-- everyone); attempts/states are private per signed-in user.
alter table questions             enable row level security;
alter table solutions             enable row level security;
alter table user_attempts         enable row level security;
alter table user_question_states  enable row level security;

create policy "questions are readable by any signed-in user"
  on questions for select to authenticated using (true);
create policy "solutions are readable by any signed-in user"
  on solutions for select to authenticated using (true);

create policy "users manage their own attempts"
  on user_attempts for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users manage their own question states"
  on user_question_states for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
